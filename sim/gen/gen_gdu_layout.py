"""Generates gdu_layout.h: the memory layout of Sim.GameDataUpdate as the game's C# code sees it.

Reads the decompiled C# (ILSpy output) and computes struct sizes with the same rules the CLR
uses for blittable sequential structs: each field aligned to min(natural alignment, Pack).
"""
import glob
import re
import sys

PRIMS = {
    'byte': 1, 'sbyte': 1, 'bool': 1,
    'short': 2, 'ushort': 2, 'char': 2,
    'int': 4, 'uint': 4, 'float': 4,
    'long': 8, 'ulong': 8, 'double': 8, 'IntPtr': 8, 'UIntPtr': 8,
}


# Bytes per game cell of the property textures, from the allocations in GameData::GameData.
TEXEL_SIZES = {
    'propertyTextureFlow': 8,
    'propertyTextureLiquid': 4,
    'propertyTextureLiquidData': 4,
    'propertyTextureMaterialData': 4,
    'propertyTextureExposedToSunlight': 1,
}

# Bytes the original leaves uninitialized in some entries, masked like padding: a new
# ElementChunkInfo slot is never initialized (its default constructor does nothing), so the first
# deltaKJ of a new debris item is heap garbage plus the step's energy.
UNINITIALIZED_BYTES = {
    'elementChunkInfos': [4, 5, 6, 7],
}

def load_sources(root):
    return {f: open(f, encoding='utf-8', errors='ignore').read()
            for f in glob.glob(root + '/**/*.cs', recursive=True)}


def index_types(sources):
    structs, enums = {}, {}
    for text in sources.values():
        for m in re.finditer(r'(\[StructLayout\(([^\]]*)\)\]\s*)?(?:public |private |internal )*(?:unsafe )?'
                             r'struct (\w+)\s*(?::[^{]*)?\{', text):
            name = m.group(3)
            attrs = m.group(2) or ''
            pack = re.search(r'Pack = (\d+)', attrs)
            body_start = m.end()
            depth, i = 1, body_start
            while depth and i < len(text):
                depth += {'{': 1, '}': -1}.get(text[i], 0)
                i += 1
            body = text[body_start:i - 1]
            # Drop nested type bodies and methods so only this struct's own fields remain.
            flat, depth = [], 0
            for ch in body:
                if ch == '{':
                    depth += 1
                elif ch == '}':
                    depth -= 1
                elif depth == 0:
                    flat.append(ch)
            fields = re.findall(r'^\s*public (?:unsafe )?(?!static|const)([\w.]+\*?) (\w+);',
                                ''.join(flat), re.M)
            structs.setdefault(name, (int(pack.group(1)) if pack else 8, fields))
        for m in re.finditer(r'enum (\w+)\s*(?::\s*(\w+))?', text):
            enums.setdefault(m.group(1), PRIMS.get(m.group(2) or 'int', 4))
    return structs, enums


def size_align(t, structs, enums, seen=()):
    t = t.split('.')[-1]
    if t.endswith('*'):
        return 8, 8
    if t in PRIMS:
        return PRIMS[t], PRIMS[t]
    if t in enums:
        return enums[t], enums[t]
    if t == 'HashedString':
        return 4, 4
    if t in structs and t not in seen:
        pack, fields = structs[t]
        off, maxal = 0, 1
        for ft, _ in fields:
            s, a = size_align(ft, structs, enums, seen + (t,))
            a = min(a, pack)
            off = (off + a - 1) // a * a + s
            maxal = max(maxal, a)
        return (off + maxal - 1) // maxal * maxal, maxal
    raise KeyError(t)


def padding_bytes(t, structs, enums):
    """Byte offsets inside struct t that no field covers, or that belong to fields named pad*
    (padding the game never reads)."""
    t = t.split('.')[-1]
    if t not in structs:
        return []
    pack, fields = structs[t]
    covered, off = set(), 0
    for ft, fn in fields:
        s, a = size_align(ft, structs, enums)
        a = min(a, pack)
        off = (off + a - 1) // a * a
        if not fn.startswith('pad'):
            covered.update(range(off, off + s))
        off += s
    total = size_align(t, structs, enums)[0]
    return [i for i in range(total) if i not in covered]


def main(root, out):
    structs, enums = index_types(load_sources(root))
    pack, fields = structs['GameDataUpdate']
    lines = ['// Generated by sim/gen/gen_gdu_layout.py from the decompiled C#. Do not edit.',
             '#pragma once', '#include <stddef.h>', '',
             '// padding: up to 8 byte offsets inside each element that are padding, -1 terminated.',
             '// The replay zeroes them before hashing: the original leaves stack garbage there.',
             'typedef struct { const char *name; int count_offset; int ptr_offset; int elem_size; int padding[9]; }'
             ' GduArray;',
             'typedef struct { const char *name; int ptr_offset; int elem_size; } GduCellArray;', '']
    off = 0
    offsets = {}
    for ft, fn in fields:
        s, a = size_align(ft, structs, enums)
        a = min(a, pack)
        off = (off + a - 1) // a * a
        offsets[fn] = (off, ft)
        off += s
    lines.append(f'#define GDU_SIZE {off}')
    lines.append(f'#define GDU_NUM_FRAMES_OFFSET {offsets["numFramesProcessed"][0]}')
    arrays, cells, textures = [], [], []
    names = [fn for _, fn in fields]
    for i, (ft, fn) in enumerate(fields):
        if not ft.endswith('*') and ft != 'IntPtr':
            continue
        prev = names[i - 1] if i else ''
        if prev.lower() == 'num' + fn.lower() and offsets[prev][1] == 'int':
            elem = size_align(ft[:-1], structs, enums)[0]
            pads = padding_bytes(ft[:-1], structs, enums)
            pads += UNINITIALIZED_BYTES.get(fn, [])
            if len(pads) > 8:
                raise SystemExit(f'{ft}: more than 8 padding bytes')
            pad_list = ', '.join(str(p) for p in pads + [-1])
            arrays.append(f'    {{"{fn}", {offsets[prev][0]}, {offsets[fn][0]}, {elem}, {{{pad_list}}}}},')
        elif ft == 'IntPtr':
            textures.append(f'    {{"{fn}", {offsets[fn][0]}, {TEXEL_SIZES.get(fn, 0)}}},')
        else:
            elem = size_align(ft[:-1], structs, enums)[0]
            cells.append(f'    {{"{fn}", {offsets[fn][0]}, {elem}}},')
    lines += ['static const GduArray kGduArrays[] = {'] + arrays + ['};']
    lines += ['static const GduCellArray kGduCellArrays[] = {'] + cells + ['};']
    lines += ['// Property textures, one texel per game cell (texel size 0: not hashed).',
              'static const GduCellArray kGduTextures[] = {'] + textures + ['};']
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
