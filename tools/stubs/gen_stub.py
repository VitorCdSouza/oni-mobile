"""Generate a C stub library that exports the given functions and does nothing.

Every function returns 0 (null, false), which is what the game sees from a
platform service that is not there.

Usage: python3 gen_stub.py <names.txt> <out.c>
"""

import sys


def main():
    names = [line.strip() for line in open(sys.argv[1]) if line.strip()]
    with open(sys.argv[2], "w") as out:
        out.write("// Generated by tools/stubs/gen_stub.py. Do not edit.\n")
        out.write("// Each function ignores its arguments and returns 0.\n\n")
        for name in names:
            out.write(f'__attribute__((visibility("default"))) long {name}(void) {{ return 0; }}\n')


if __name__ == "__main__":
    main()
